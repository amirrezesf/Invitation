export function getInviteTypeMeta(type: InviteType): InviteTypeMeta {
  return INVITE_TYPES.find((t) => t.id === type) ?? INVITE_TYPES[0];
}

export function generateConvinceReasons(
  cafe: Pick<CafeConfig, 'name' | 'menuItems' | 'discount'>,
  type: InviteType,
  prePickedDrink?: MenuItem
): string[] {
  const menu = cafe.menuItems.length > 0 ? cafe.menuItems : [];
  const randomDrink =
    prePickedDrink ||
    menu.find((m) => m.category !== 'dessert') ||
    { name: 'لته رز و وانیل', emoji: '🌹', price: 185000 };
  const randomDessert =
    menu.find((m) => m.category === 'dessert') ||
    { name: 'چیزکیک سن‌سباستین', emoji: '🍰', price: 240000 };

  const typeReasonMap: Record<InviteType, string> = {
    date: 'اینجور قرارهای بی‌برنامه معمولاً تبدیل به قشنگ‌ترین خاطره هفته میشن.',
    friends: 'جمع رفقا بدون حضور تو نصف انرژی همیشه‌اش رو هم نداره!',
    study: 'تحقیقات نشون داده تمرکز کنار یه فنجون قهوه تو کافه ۳ برابر خونه است!',
    vent: 'گوشی رو بذار کنار؛ هیچ‌چیز جای حرف زدن رودررو و سبک شدن رو نمی‌گیره.',
    owe: 'کی از قهوه مفت و برنده بودن در شرط‌بندی بدش میاد؟ حق مسلمته!',
    apology: 'طرف حسابی پشیمونه و حتی حاضر شده با شیرینی از دلت دربیاره؛ یه فرصت بده!',
    surprise: 'تا قبول نکنی نمی‌فهمی چه جای باحالی قراره بری؛ ریسک کوچیک، حال خوب بزرگ!',
  };

  return [
    `${randomDrink.emoji} توی منوی ${cafe.name} «${randomDrink.name}» (${formatToman(randomDrink.price)}) منتظرته — مگه میشه ازش گذشت؟`,
    `${randomDessert.emoji} کنار قهوه‌مون یه برش «${randomDessert.name}» می‌چسبه که خستگی کل هفته رو بشوره ببره!`,
    `🎟️ فقط با قبول کردن همین دعوت‌نامه، یه بلیت ${toPersianDigits(cafe.discount.percent)}٪ تخفیف (${cafe.discount.label}) برات صادر میشه!`,
    `✨ ${typeReasonMap[type]}`,
  ];
}

export function getRandomWittyLine(type: InviteType, seed = 0): string {
  const meta = getInviteTypeMeta(type);
  return meta.wittyLines[Math.abs(seed) % meta.wittyLines.length];
}
